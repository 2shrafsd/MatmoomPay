/// Spacing scale (logical pixels), 4-point steps.
abstract final class AppSpacing {
  static const double xxs = 2;
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 20;
  static const double xxl = 24;
  static const double xxxl = 32;
  static const double huge = 48;

  /// Horizontal page margin on phones.
  static const double page = 16;

  /// Gap between product tiles.
  static const double gridGutter = 12;

  /// Gap between product rows.
  static const double gridRowGap = 24;

  /// Widest the content column grows on tablets.
  static const double maxContentWidth = 1100;

  /// Widest a form or result column grows.
  static const double maxFormWidth = 560;
}
